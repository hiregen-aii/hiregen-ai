// n8n-facing webhooks — auth via rotating API key + HMAC signature.
// POST /api/v1/webhooks/n8n/signal-ingest   — Team 2 (2.1)
// POST /api/v1/webhooks/n8n/step-complete   — Team 4
const {
    createHiringSignal
} = require("../services/hiring-signals.service");

const { z } = require("zod");

const {
    runDiscoveryAgent
} = require("../agents/discovery.agent");

/**
 * Payload accepted from n8n workflow.
 *
 * Supports multiple field aliases
 * coming from different job providers.
 */

const signalSchema = z.object({
    company: z.string().optional(),
    companyName: z.string().optional(),
    organization: z.string().optional(),
    employer: z.string().optional(),

    role: z.string().optional(),
    title: z.string().optional(),
    jobTitle: z.string().optional(),
    position: z.string().optional(),

    description: z.string().optional(),
    jobDescription: z.string().optional(),

    location: z.string().optional(),

    source: z.string().optional(),

    sourceUrl: z.string().optional(),
    url: z.string().optional()
});

module.exports = async function (fastify) {

    /**
     * ---------------------------------------------------------
     * POST /api/v1/webhooks/n8n/signal-ingest
     *
     * Receives hiring signals generated by n8n.
     *
     * Responsibilities:
     * - Validate incoming payload
     * - Normalize hiring signal
     * - Forward the normalized signal to the queue layer
     *
     * Response:
     * - 202 Accepted
     *
     * Owner:
     * Team 2 (Module 2.1)
     * ---------------------------------------------------------
     */
    fastify.post(
        "/signal-ingest",
        async (
            request,
            reply
        ) => {

            fastify.log.info("Received hiring signal from n8n.");

            try {

                /**
                 * =====================================
                 * TODO (Security Team)
                 *
                 * 1. Validate rotating API key.
                 * 2. Verify HMAC signature.
                 * 3. Reject replay attacks.
                 * 4. Rate-limit webhook traffic.
                 *
                 * =====================================
                 */

                const payload = signalSchema.parse(request.body ?? {});

                const normalizedSignal =
                    await runDiscoveryAgent(payload);


                /**
                 * =====================================
                 * TODO (Infrastructure Team)
                 *
                 * Publish normalizedSignal to BullMQ
                 * for downstream enrichment and
                 * classification agents.
                 *
                 * Queue Name:
                 * hiring-signals
                 *
                 * Payload:
                 * normalizedSignal
                 *
                 * =====================================
                 */

                return reply.code(202).send({

                    success: true,

                    message:
                        "Hiring signal stored successfully.",

                    data: hiringSignal

                });

            }

            catch (error) {
                console.error(error);

                fastify.log.error(
                { error },
                "Failed to process hiring signal."
            );

                if (error instanceof z.ZodError) {

                    return reply.code(400).send({

                    success: false,

                    message: "Invalid webhook payload.",

                    requestId: request.id,

                    errors: error.flatten()

                });

                }

                return reply.code(500).send({

                    success: false,

                    message: "Unable to process hiring signal.",

                    requestId: request.id

                });

            }

        }
    );

}